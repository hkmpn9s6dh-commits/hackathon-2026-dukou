def pad_plan():
    """[(起始小节, 持续小节数, 和弦名, 亮度 0..1)]"""
    plan = []
    plan.append((1, 13, "Dm9", 0.12))                       # I：一片，不动
    for b, c in [(14, "Dm9"), (18, "Gm9"), (22, "Dm9")]:
        plan.append((b, 4, c, 0.38))                        # II：四小节一换
    plan.append((26, 1, "Am7", 0.42))
    for b, c in [(27, "Dm"), (29, "F"), (31, "C"), (33, "G"),
                 (35, "Dm"), (37, "C")]:
        plan.append((b, 2, c, 0.75))                        # III：两小节一换
    plan.append((39, 1, "Am7", 0.7))
    for b, c in [(40, "Dm9"), (42, "Bbmaj7"), (44, "Dm"),
                 (46, "Am7"), (48, "Dm")]:
        plan.append((b, 2, c, 0.3))                         # IV：退回去
    plan.append((50, 3, "Dm", 0.18))                        # 最后一口气
    return plan


# ------------------------------------------------------------------ 旋律

def reed_plan():
    """[(起始小节, 起始拍, 动机列表, 力度, 低通 Hz 或 None)]"""
    out = []
    # I：埋着。只给一点影子，低通压到 700 Hz，听得出有东西、听不出旋律
    out.append((9, 0.0, MOTIF, 0.16, 700.0))
    # II：第一次完整出现（原调），第二次（下属方向），第三次（原调加厚）
    out.append((15, 0.0, MOTIF, 0.62, None))
    out.append((19, 0.0, transpose(MOTIF, -5), 0.5, None))   # 下五度，像对岸的回声
    out.append((23, 0.0, MOTIF, 0.72, None))
    out.append((25, 0.0, [(76, 2.0), (74, 2.0)], 0.4, None))  # 只留尾巴
    # III：上行四度（转调到 G）与五度，最高点
    out.append((27, 0.0, MOTIF, 0.85, None))
    # 转调到 G 多利亚：不是机械 +5，而是把每个音落在 G 多利亚的级数上
    # （第二个音是 B 自然，不是 B♭——B♭ 只在第四段的 B♭maj7 里出现）
    out.append((33, 0.0, [(79, 2.0), (83, 1.0), (86, 1.0), (84, 1.5), (81, 2.5)], 0.95, None))
    out.append((37, 0.0, [(81, 4.0), (79, 4.0)], 0.8, None))  # 放慢
    # IV：碎成单音，长间隔
    out.append((40, 0.0, [(74, 4.0)], 0.55, None))
    out.append((44, 2.0, [(77, 4.0)], 0.45, None))
    out.append((47, 0.0, [(77, 5.0)], 0.4, None))            # 三音
    out.append((50, 0.0, [(76, 6.0)], 0.28, None))           # 落在 9 音，不解决
    return out


