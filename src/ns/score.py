"""《渡口》Crossing at First Light —— 乐谱。

52 小节，52 BPM，4/4。四段，每段 13 小节：
  I  未亮    bar 1–13   0:00–1:00
  II 微亮    bar 14–26  1:00–2:00
  III 日出   bar 27–39  2:00–3:00
  IV 对岸    bar 40–52  3:00–4:00 + 12 s 余响

调式：D 多利亚（D Dorian）。全曲没有一个 B♭——除了第四段借来的 ♭VI（B♭maj7），
那是"对岸"变暗的一笔。动机 M 里不含 B，所以两处不会打架。

动机 M（"摆渡"）：D5 – F5 – A5 – G5 – E5，落在 9 音上，故意不解决。
节奏 2 / 1 / 1 / 1.5 / 2.5 拍，共 8 拍 = 2 小节。
"""

from __future__ import annotations

BPM = 52.0
BEAT = 60.0 / BPM
BAR = 4 * BEAT
BARS = 52
TAIL_S = 12.0
TOTAL_S = round(BARS * BAR + TAIL_S, 6)   # 240 + 12 = 252.0（round 掉浮点尾巴）

# 小节/拍 -> 秒（小节从 1 开始）
def bt(bar: int, beat: float = 0.0) -> float:
    return (bar - 1) * BAR + beat * BEAT


# 动机 M：音高（MIDI）与时长（拍）
MOTIF = [(74, 2.0), (77, 1.0), (81, 1.0), (79, 1.5), (76, 2.5)]


def transpose(motif, semitones: int):
    return [(m + semitones, d) for m, d in motif]


